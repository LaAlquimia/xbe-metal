std::string CppEmitter::emit_translation_unit(
    const xbe::XbeParser& parser,
    const std::vector<DecodedInstruction>& instructions) const
{
    std::ostringstream out;

    const std::string title_name = parser.get_title_name().empty() ? "Unknown Xbox Title" : parser.get_title_name();

    out << "// ============================================================================\n";
    out << "// Auto-generated by xbe-recomp (xbe-metal Static Recompiler)\n";
    out << "// Title Name  : " << title_name << "\n";
    out << "// Title ID    : " << fmt_hex32(parser.get_title_id()) << "\n";
    out << "// Entry Point : " << fmt_hex32(parser.get_entry_point()) << "\n";
    out << "// ============================================================================\n\n";

    out << "#include \"runtime/core/memory.hpp\"\n";
    out << "#include \"runtime/core/kernel.hpp\"\n";
    out << "#include \"recompiler/cpp_emitter.hpp\"\n";
    out << "#include <cstdint>\n\n";

    out << "void guest_entry(\n";
    out << "    xbe::recompiler::CpuContext& ctx,\n";
    out << "    runtime::core::XboxMemory& mem,\n";
    out << "    runtime::core::XboxKernel& kernel)\n";
    out << "{\n";
    out << "    if (ctx.esp == 0) {\n";
    out << "        ctx.esp = 0x0008F000;\n";
    out << "        ctx.ebp = 0x0008F000;\n";
    out << "    }\n";
    out << "    mem.allocate_virtual((ctx.esp - 0x4000u) & ~0xFFFu, 0x8000u);\n\n";

    for (const auto& inst : instructions) {
        out << "    // [" << fmt_hex32(inst.address) << "] " << inst.text << "\n";
        out << "    L_" << std::uppercase << std::hex << std::setw(8) << std::setfill('0') << inst.address << std::dec << ":\n";
        out << "    ctx.eip = " << fmt_hex32(inst.address) << ";\n";

        switch (inst.mnemonic) {
            case X86Mnemonic::NOP:
                out << "    /* nop */\n";
                break;

            case X86Mnemonic::PUSH_REG:
                out << "    ctx.esp -= 4;\n";
                out << "    mem.write<uint32_t>(ctx.esp, " << ctx_reg(inst.src_reg) << ");\n";
                break;

            case X86Mnemonic::POP_REG:
                out << "    " << ctx_reg(inst.dst_reg) << " = mem.read<uint32_t>(ctx.esp);\n";
                out << "    ctx.esp += 4;\n";
                break;

            case X86Mnemonic::PUSH_IMM32:
            case X86Mnemonic::PUSH_IMM8:
                out << "    ctx.esp -= 4;\n";
                out << "    mem.write<uint32_t>(ctx.esp, " << fmt_hex32(inst.imm) << ");\n";
                break;

            case X86Mnemonic::MOV_REG_IMM32:
                out << "    " << ctx_reg(inst.dst_reg) << " = " << fmt_hex32(inst.imm) << ";\n";
                break;

            case X86Mnemonic::MOV_REG_REG:
                out << "    " << ctx_reg(inst.dst_reg) << " = " << ctx_reg(inst.src_reg) << ";\n";
                break;

            case X86Mnemonic::MOV_REG_MEM:
                out << "    " << ctx_reg(inst.dst_reg) << " = mem.read<uint32_t>(" << emit_mem_addr_expr(inst) << ");\n";
                break;

            case X86Mnemonic::MOV_MEM_REG:
                out << "    mem.write<uint32_t>(" << emit_mem_addr_expr(inst) << ", " << ctx_reg(inst.src_reg) << ");\n";
                break;

            case X86Mnemonic::LEA_REG_MEM:
                out << "    " << ctx_reg(inst.dst_reg) << " = " << emit_mem_addr_expr(inst) << ";\n";
                break;

            case X86Mnemonic::ADD_REG_IMM:
                out << "    " << ctx_reg(inst.dst_reg) << " += " << fmt_hex32(inst.imm) << ";\n";
                break;

            case X86Mnemonic::ADD_REG_REG:
                out << "    " << ctx_reg(inst.dst_reg) << " += " << ctx_reg(inst.src_reg) << ";\n";
                break;

            case X86Mnemonic::SUB_REG_IMM:
                out << "    " << ctx_reg(inst.dst_reg) << " -= " << fmt_hex32(inst.imm) << ";\n";
                break;

            case X86Mnemonic::SUB_REG_REG:
                out << "    " << ctx_reg(inst.dst_reg) << " -= " << ctx_reg(inst.src_reg) << ";\n";
                break;

            case X86Mnemonic::XOR_REG_REG:
                if (inst.dst_reg == inst.src_reg) {
                    out << "    " << ctx_reg(inst.dst_reg) << " = 0;\n";
                } else {
                    out << "    " << ctx_reg(inst.dst_reg) << " ^= " << ctx_reg(inst.src_reg) << ";\n";
                }
                break;

            case X86Mnemonic::CMP_REG_IMM:
                out << "    ctx.eflags = (" << ctx_reg(inst.dst_reg) << " == " << fmt_hex32(inst.imm)
                    << ") ? xbe::recompiler::CpuContext::EFLAGS_ZF : 0u;\n";
                break;

            case X86Mnemonic::CMP_REG_REG:
                out << "    ctx.eflags = (" << ctx_reg(inst.dst_reg) << " == " << ctx_reg(inst.src_reg)
                    << ") ? xbe::recompiler::CpuContext::EFLAGS_ZF : 0u;\n";
                break;

            case X86Mnemonic::TEST_REG_REG:
                out << "    ctx.eflags = ((" << ctx_reg(inst.dst_reg) << " & " << ctx_reg(inst.src_reg)
                    << ") == 0) ? xbe::recompiler::CpuContext::EFLAGS_ZF : 0u;\n";
                break;

            case X86Mnemonic::CALL_INDIRECT_MEM: {
                const auto* imp = find_kernel_import(parser, inst.mem_address);
                if (imp) {
                    out << "    // Xbox Kernel Thunk: " << imp->name << " (ordinal " << imp->ordinal << ")\n";
                    out << "    ctx.eax = kernel.dispatch(" << imp->ordinal << ", mem, {\n";
                    out << "        mem.read<uint32_t>(ctx.esp),\n";
                    out << "        mem.read<uint32_t>(ctx.esp + 4),\n";
                    out << "        mem.read<uint32_t>(ctx.esp + 8),\n";
                    out << "        mem.read<uint32_t>(ctx.esp + 12)\n";
                    out << "    });\n";
                } else {
                    out << "    {\n";
                    out << "        uint32_t thunk_val = mem.read<uint32_t>(" << fmt_hex32(inst.mem_address) << ");\n";
                    out << "        if ((thunk_val & 0x80000000u) != 0) {\n";
                    out << "            ctx.eax = kernel.dispatch(thunk_val & 0x7FFFFFFFu, mem, {mem.read<uint32_t>(ctx.esp)});\n";
                    out << "        }\n";
                    out << "    }\n";
                }
                break;
            }

            case X86Mnemonic::CALL_REL32:
                out << "    // Direct near call to " << fmt_hex32(inst.imm) << "\n";
                break;

            case X86Mnemonic::JMP_REL32:
            case X86Mnemonic::JMP_REL8:
                out << "    goto L_" << std::uppercase << std::hex << std::setw(8) << std::setfill('0') << inst.imm << std::dec << ";\n";
                break;

            case X86Mnemonic::JE_REL8:
                out << "    if ((ctx.eflags & xbe::recompiler::CpuContext::EFLAGS_ZF) != 0) goto L_"
                    << std::uppercase << std::hex << std::setw(8) << std::setfill('0') << inst.imm << std::dec << ";\n";
                break;

            case X86Mnemonic::JNE_REL8:
                out << "    if ((ctx.eflags & xbe::recompiler::CpuContext::EFLAGS_ZF) == 0) goto L_"
                    << std::uppercase << std::hex << std::setw(8) << std::setfill('0') << inst.imm << std::dec << ";\n";
                break;

            case X86Mnemonic::RET:
                out << "    ctx.halted = true;\n";
                out << "    return;\n";
                break;

            case X86Mnemonic::RET_IMM16:
                out << "    ctx.esp += " << fmt_hex32(inst.imm) << ";\n";
                out << "    ctx.halted = true;\n";
                out << "    return;\n";
                break;

            case X86Mnemonic::INT3:
                out << "    ctx.halted = true;\n";
                out << "    return;\n";
                break;

            case X86Mnemonic::UNKNOWN:
            default:
                out << "    /* unhandled opcode */\n";
                break;
        }
        out << "\n";
    }

    out << "}\n";
    return out.str();
}

bool CppEmitter::execute_instructions(
    const std::vector<DecodedInstruction>& instructions,
    const xbe::XbeParser& parser,
    CpuContext& ctx,
    runtime::core::XboxMemory& mem,
    runtime::core::XboxKernel& kernel) const
{
    if (instructions.empty()) {
        return false;
    }

    // Map XBE headers and sections into XboxMemory if parser is valid
    if (parser.is_valid()) {
        if (!parser.get_raw_headers().empty() && !mem.is_valid_va(parser.get_header().base_address)) {
            mem.map_headers(parser.get_header(), parser.get_raw_headers());
        }
        for (const auto& sec : parser.get_sections()) {
            if (sec.header.virtual_size > 0 && !mem.is_valid_va(sec.header.virtual_address)) {
                mem.map_section(sec.header, sec.data);
            }
        }
        if (parser.get_kernel_thunk_address() != 0 && mem.is_valid_va(parser.get_kernel_thunk_address())) {
            kernel.install_thunks(mem, parser.get_kernel_thunk_address());
        }
    }

    // Ensure stack pointer and stack pages are valid
    if (ctx.esp < 0x00010000u) {
        ctx.esp = 0x0008F000u;
        ctx.ebp = 0x0008F000u;
    }
    uint32_t stack_base = (ctx.esp - 0x4000u) & ~0xFFFu;
    mem.allocate_virtual(stack_base, 0x8000u, runtime::core::PAGE_PROT_READ | runtime::core::PAGE_PROT_WRITE);

    // Index instruction addresses for local branches
    std::unordered_map<uint32_t, size_t> addr_to_idx;
    addr_to_idx.reserve(instructions.size());
    for (size_t i = 0; i < instructions.size(); ++i) {
        addr_to_idx[instructions[i].address] = i;
    }

    ctx.halted = false;
    size_t pc = 0;
    size_t steps = 0;
    constexpr size_t MAX_STEPS = 10000;

    while (pc < instructions.size() && !ctx.halted && steps++ < MAX_STEPS) {
        const auto& inst = instructions[pc];
        ctx.eip = inst.address;
        bool jumped = false;

        switch (inst.mnemonic) {
            case X86Mnemonic::NOP:
                break;

            case X86Mnemonic::PUSH_REG: {
                uint32_t val = ctx.reg(inst.src_reg);
                ctx.esp -= 4;
                mem.write<uint32_t>(ctx.esp, val);
                break;
            }

            case X86Mnemonic::POP_REG: {
                uint32_t val = mem.read<uint32_t>(ctx.esp);
                ctx.esp += 4;
                ctx.reg(inst.dst_reg) = val;
                break;
            }

            case X86Mnemonic::PUSH_IMM32:
            case X86Mnemonic::PUSH_IMM8:
                ctx.esp -= 4;
                mem.write<uint32_t>(ctx.esp, inst.imm);
                break;

            case X86Mnemonic::MOV_REG_IMM32:
                ctx.reg(inst.dst_reg) = inst.imm;
                break;

            case X86Mnemonic::MOV_REG_REG:
                ctx.reg(inst.dst_reg) = ctx.reg(inst.src_reg);
                break;

            case X86Mnemonic::MOV_REG_MEM: {
                uint32_t ea = compute_effective_address(inst, ctx, inst.src_reg);
                ctx.reg(inst.dst_reg) = mem.read<uint32_t>(ea);
                break;
            }

            case X86Mnemonic::MOV_MEM_REG: {
                uint32_t ea = compute_effective_address(inst, ctx, inst.dst_reg);
                mem.write<uint32_t>(ea, ctx.reg(inst.src_reg));
                break;
            }

            case X86Mnemonic::LEA_REG_MEM: {
                uint32_t ea = compute_effective_address(inst, ctx, inst.src_reg);
                ctx.reg(inst.dst_reg) = ea;
                break;
            }

            case X86Mnemonic::ADD_REG_IMM: {
                uint32_t res = ctx.reg(inst.dst_reg) + inst.imm;
                ctx.reg(inst.dst_reg) = res;
                update_flags(ctx, res);
                break;
            }

            case X86Mnemonic::ADD_REG_REG: {
                uint32_t res = ctx.reg(inst.dst_reg) + ctx.reg(inst.src_reg);
                ctx.reg(inst.dst_reg) = res;
                update_flags(ctx, res);
                break;
            }

            case X86Mnemonic::SUB_REG_IMM: {
                uint32_t res = ctx.reg(inst.dst_reg) - inst.imm;
                ctx.reg(inst.dst_reg) = res;
                update_flags(ctx, res);
                break;
            }

            case X86Mnemonic::SUB_REG_REG: {
                uint32_t res = ctx.reg(inst.dst_reg) - ctx.reg(inst.src_reg);
                ctx.reg(inst.dst_reg) = res;
                update_flags(ctx, res);
                break;
            }

            case X86Mnemonic::XOR_REG_REG: {
                uint32_t res = ctx.reg(inst.dst_reg) ^ ctx.reg(inst.src_reg);
                ctx.reg(inst.dst_reg) = res;
                update_flags(ctx, res);
                break;
            }

            case X86Mnemonic::CMP_REG_IMM: {
                uint32_t res = ctx.reg(inst.dst_reg) - inst.imm;
                update_flags(ctx, res);
                break;
            }

            case X86Mnemonic::CMP_REG_REG: {
                uint32_t res = ctx.reg(inst.dst_reg) - ctx.reg(inst.src_reg);
                update_flags(ctx, res);
                break;
            }

            case X86Mnemonic::TEST_REG_REG: {
                uint32_t res = ctx.reg(inst.dst_reg) & ctx.reg(inst.src_reg);
                update_flags(ctx, res);
                break;
            }

            case X86Mnemonic::CALL_INDIRECT_MEM: {
                uint32_t ordinal = 0;
                if (const auto* imp = find_kernel_import(parser, inst.mem_address)) {
                    ordinal = imp->ordinal;
                } else if (mem.is_valid_va(inst.mem_address)) {
                    uint32_t thunk_val = mem.read<uint32_t>(inst.mem_address);
                    if ((thunk_val & 0x80000000u) != 0) {
                        ordinal = thunk_val & 0x7FFFFFFFu;
                    }
                }

                if (ordinal != 0) {
                    std::vector<uint32_t> args;
                    args.reserve(4);
                    for (uint32_t i = 0; i < 4; ++i) {
                        uint32_t arg_va = ctx.esp + (i * 4);
                        if (mem.is_valid_va(arg_va)) {
                            args.push_back(mem.read<uint32_t>(arg_va));
                        }
                    }
                    ctx.eax = kernel.dispatch(ordinal, mem, args);
                }
                break;
            }

            case X86Mnemonic::CALL_REL32: {
                auto it = addr_to_idx.find(inst.imm);
                if (it != addr_to_idx.end()) {
                    ctx.esp -= 4;
                    mem.write<uint32_t>(ctx.esp, inst.address + inst.size);
                    pc = it->second;
                    jumped = true;
                }
                break;
            }

            case X86Mnemonic::JMP_REL32:
            case X86Mnemonic::JMP_REL8: {
                auto it = addr_to_idx.find(inst.imm);
                if (it != addr_to_idx.end()) {
                    pc = it->second;
                    jumped = true;
                }
                break;
            }

            case X86Mnemonic::JE_REL8: {
                if ((ctx.eflags & CpuContext::EFLAGS_ZF) != 0) {
                    auto it = addr_to_idx.find(inst.imm);
                    if (it != addr_to_idx.end()) {
                        pc = it->second;
                        jumped = true;
                    }
                }
                break;
            }

            case X86Mnemonic::JNE_REL8: {
                if ((ctx.eflags & CpuContext::EFLAGS_ZF) == 0) {
                    auto it = addr_to_idx.find(inst.imm);
                    if (it != addr_to_idx.end()) {
                        pc = it->second;
                        jumped = true;
                    }
                }
                break;
            }

            case X86Mnemonic::RET:
                ctx.halted = true;
                break;

            case X86Mnemonic::RET_IMM16:
                ctx.esp += inst.imm;
                ctx.halted = true;
                break;

            case X86Mnemonic::INT3:
                ctx.halted = true;
                break;

            case X86Mnemonic::UNKNOWN:
            default:
                return false;
        }

        if (!jumped) {
            ++pc;
        }
    }

    return true;
}

