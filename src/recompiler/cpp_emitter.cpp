std::string fmt_hex32(uint32_t v) {
    char buf[16];
    std::snprintf(buf, sizeof(buf), "0x%08X", v);
    return buf;
}

std::string ctx_reg(X86Reg r) {
    return std::string("ctx.") + reg_name(r);
}

std::string emit_mem_addr_expr(const DecodedInstruction& inst) {
    if (inst.src_reg == X86Reg::NONE && inst.dst_reg == X86Reg::NONE) {
        return fmt_hex32(inst.mem_address);
    }
    X86Reg base = (inst.mnemonic == X86Mnemonic::MOV_MEM_REG) ? inst.dst_reg : inst.src_reg;
    if (base == X86Reg::NONE) {
        return fmt_hex32(inst.mem_address);
    }
    if (inst.disp == 0) {
        return ctx_reg(base);
    }
    if (inst.disp > 0) {
        return "(" + ctx_reg(base) + " + " + fmt_hex32(static_cast<uint32_t>(inst.disp)) + ")";
    }
    uint32_t abs_disp = static_cast<uint32_t>(-static_cast<int64_t>(inst.disp));
    return "(" + ctx_reg(base) + " - " + fmt_hex32(abs_disp) + ")";
}

const xbe::KernelImport* find_kernel_import(const xbe::XbeParser& parser, uint32_t thunk_va) noexcept {
    for (const auto& imp : parser.get_kernel_imports()) {
        if (imp.thunk_address == thunk_va) {
            return &imp;
        }
    }
    return nullptr;
}

void update_flags(CpuContext& ctx, uint32_t result) noexcept {
    ctx.eflags = 0;
    if (result == 0) {
        ctx.eflags |= CpuContext::EFLAGS_ZF;
    }
    if ((result & 0x80000000u) != 0) {
        ctx.eflags |= CpuContext::EFLAGS_SF;
    }
}

uint32_t compute_effective_address(const DecodedInstruction& inst, const CpuContext& ctx, X86Reg base_reg) noexcept {
    if (base_reg == X86Reg::NONE) {
        return inst.mem_address;
    }
    return static_cast<uint32_t>(static_cast<int64_t>(ctx.reg(base_reg)) + inst.disp);
}

